#include "Math/Matrix4x4.h"

Matrix4x4 Matrix4x4::Inversed() const noexcept {
	Matrix4x4 result{};

	//行列式
	float det =
		(m[0][0] * m[1][1] * m[2][2] * m[3][3]) + (m[0][0] * m[1][2] * m[2][3] * m[3][1]) + (m[0][0] * m[1][3] * m[2][1] * m[3][2]) -
		(m[0][0] * m[1][3] * m[2][2] * m[3][1]) - (m[0][0] * m[1][2] * m[2][1] * m[3][3]) - (m[0][0] * m[1][1] * m[2][3] * m[3][2]) -
		(m[0][1] * m[1][0] * m[2][2] * m[3][3]) - (m[0][2] * m[1][0] * m[2][3] * m[3][1]) - (m[0][3] * m[1][0] * m[2][1] * m[3][2]) +
		(m[0][3] * m[1][0] * m[2][2] * m[3][1]) + (m[0][2] * m[1][0] * m[2][1] * m[3][3]) + (m[0][1] * m[1][0] * m[2][3] * m[3][2]) +
		(m[0][1] * m[1][2] * m[2][0] * m[3][3]) + (m[0][2] * m[1][3] * m[2][0] * m[3][1]) + (m[0][3] * m[1][1] * m[2][0] * m[3][2]) -
		(m[0][3] * m[1][2] * m[2][0] * m[3][1]) - (m[0][2] * m[1][1] * m[2][0] * m[3][3]) - (m[0][1] * m[1][3] * m[2][0] * m[3][2]) -
		(m[0][1] * m[1][2] * m[2][3] * m[3][0]) - (m[0][2] * m[1][3] * m[2][1] * m[3][0]) - (m[0][3] * m[1][1] * m[2][2] * m[3][0]) +
		(m[0][3] * m[1][2] * m[2][1] * m[3][0]) + (m[0][2] * m[1][1] * m[2][3] * m[3][0]) + (m[0][1] * m[1][3] * m[2][2] * m[3][0]);

	float invDet = 1.0f / det;

	/*
	0行目
	--------------------*/

	//0列
	result.m[0][0] =
		m[1][1] * m[2][2] * m[3][3] +
		m[1][2] * m[2][3] * m[3][1] +
		m[1][3] * m[2][1] * m[3][2] -
		m[1][3] * m[2][2] * m[3][1] -
		m[1][2] * m[2][1] * m[3][3] -
		m[1][1] * m[2][3] * m[3][2];

	//1列
	result.m[0][1] =
		-m[0][1] * m[2][2] * m[3][3] -
		m[0][2] * m[2][3] * m[3][1] -
		m[0][3] * m[2][1] * m[3][2] +
		m[0][3] * m[2][2] * m[3][1] +
		m[0][2] * m[2][1] * m[3][3] +
		m[0][1] * m[2][3] * m[3][2];

	//2列
	result.m[0][2] =
		m[0][1] * m[1][2] * m[3][3] +
		m[0][2] * m[1][3] * m[3][1] +
		m[0][3] * m[1][1] * m[3][2] -
		m[0][3] * m[1][2] * m[3][1] -
		m[0][2] * m[1][1] * m[3][3] -
		m[0][1] * m[1][3] * m[3][2];

	//3列
	result.m[0][3] =
		-m[0][1] * m[1][2] * m[2][3] -
		m[0][2] * m[1][3] * m[2][1] -
		m[0][3] * m[1][1] * m[2][2] +
		m[0][3] * m[1][2] * m[2][1] +
		m[0][2] * m[1][1] * m[2][3] +
		m[0][1] * m[1][3] * m[2][2];

	/*
	1行目
	--------------------*/

	//0列
	result.m[1][0] =
		-m[1][0] * m[2][2] * m[3][3] -
		m[1][2] * m[2][3] * m[3][0] -
		m[1][3] * m[2][0] * m[3][2] +
		m[1][3] * m[2][2] * m[3][0] +
		m[1][2] * m[2][0] * m[3][3] +
		m[1][0] * m[2][3] * m[3][2];

	//1列
	result.m[1][1] =
		m[0][0] * m[2][2] * m[3][3] +
		m[0][2] * m[2][3] * m[3][0] +
		m[0][3] * m[2][0] * m[3][2] -
		m[0][3] * m[2][2] * m[3][0] -
		m[0][2] * m[2][0] * m[3][3] -
		m[0][0] * m[2][3] * m[3][2];

	//2列
	result.m[1][2] =
		-m[0][0] * m[1][2] * m[3][3] -
		m[0][2] * m[1][3] * m[3][0] -
		m[0][3] * m[1][0] * m[3][2] +
		m[0][3] * m[1][2] * m[3][0] +
		m[0][2] * m[1][0] * m[3][3] +
		m[0][0] * m[1][3] * m[3][2];

	//3列
	result.m[1][3] =
		m[0][0] * m[1][2] * m[2][3] +
		m[0][2] * m[1][3] * m[2][0] +
		m[0][3] * m[1][0] * m[2][2] -
		m[0][3] * m[1][2] * m[2][0] -
		m[0][2] * m[1][0] * m[2][3] -
		m[0][0] * m[1][3] * m[2][2];
	/*
	2行目
	--------------------*/

	//0列
	result.m[2][0] =
		m[1][0] * m[2][1] * m[3][3] +
		m[1][1] * m[2][3] * m[3][0] +
		m[1][3] * m[2][0] * m[3][1] -
		m[1][3] * m[2][1] * m[3][0] -
		m[1][1] * m[2][0] * m[3][3] -
		m[1][0] * m[2][3] * m[3][1];

	//1列
	result.m[2][1] =
		-m[0][0] * m[2][1] * m[3][3] -
		m[0][1] * m[2][3] * m[3][0] -
		m[0][3] * m[2][0] * m[3][1] +
		m[0][3] * m[2][1] * m[3][0] +
		m[0][1] * m[2][0] * m[3][3] +
		m[0][0] * m[2][3] * m[3][1];

	//2列
	result.m[2][2] =
		m[0][0] * m[1][1] * m[3][3] +
		m[0][1] * m[1][3] * m[3][0] +
		m[0][3] * m[1][0] * m[3][1] -
		m[0][3] * m[1][1] * m[3][0] -
		m[0][1] * m[1][0] * m[3][3] -
		m[0][0] * m[1][3] * m[3][1];

	//3列
	result.m[2][3] =
		-m[0][0] * m[1][1] * m[2][3] -
		m[0][1] * m[1][3] * m[2][0] -
		m[0][3] * m[1][0] * m[2][1] +
		m[0][3] * m[1][1] * m[2][0] +
		m[0][1] * m[1][0] * m[2][3] +
		m[0][0] * m[1][3] * m[2][1];

	/*
	3行目
	--------------------*/

	//0列
	result.m[3][0] =
		-m[1][0] * m[2][1] * m[3][2] -
		m[1][1] * m[2][2] * m[3][0] -
		m[1][2] * m[2][0] * m[3][1] +
		m[1][2] * m[2][1] * m[3][0] +
		m[1][1] * m[2][0] * m[3][2] +
		m[1][0] * m[2][2] * m[3][1];

	//1列
	result.m[3][1] =
		m[0][0] * m[2][1] * m[3][2] +
		m[0][1] * m[2][2] * m[3][0] +
		m[0][2] * m[2][0] * m[3][1] -
		m[0][2] * m[2][1] * m[3][0] -
		m[0][1] * m[2][0] * m[3][2] -
		m[0][0] * m[2][2] * m[3][1];

	//2列
	result.m[3][2] =
		-m[0][0] * m[1][1] * m[3][2] -
		m[0][1] * m[1][2] * m[3][0] -
		m[0][2] * m[1][0] * m[3][1] +
		m[0][2] * m[1][1] * m[3][0] +
		m[0][1] * m[1][0] * m[3][2] +
		m[0][0] * m[1][2] * m[3][1];

	//3列
	result.m[3][3] =
		m[0][0] * m[1][1] * m[2][2] +
		m[0][1] * m[1][2] * m[2][0] +
		m[0][2] * m[1][0] * m[2][1] -
		m[0][2] * m[1][1] * m[2][0] -
		m[0][1] * m[1][0] * m[2][2] -
		m[0][0] * m[1][2] * m[2][1];

	for (auto& row : result.m) {
		for (auto& element : row) {
			element *= invDet;
		}
	}

	return result;
}
